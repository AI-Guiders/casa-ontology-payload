"""Clause constructions: tense, negation, questions via English do-support.

The auxiliary does/did carries tense+agreement under negation/questions while the
main verb stays base; the declarative inflects the verb. Templates are field-stored,
so the gate's ablation and negative control prove production reads them from the field.
"""

from __future__ import annotations

import json

from casa.curriculum import (
    compose_clause,
    gate_clause_constructions,
    teach_clause_constructions,
    teach_conditioned_rule,
    teach_glossary,
)
from casa.prisms.memory.f0_math_ingest import ingest_math_bundle
from casa.prisms.memory.memory_prisms import ensure_prisms
from casa._paths import REPO_ROOT

BUNDLE = REPO_ROOT / "lab/exp_l/kb-math-concrete-schemas-l0.bundle.v1.json"
CLAUSE = REPO_ROOT / "lab/curriculum/en-clause-v1.json"
RULES = REPO_ROOT / "lab/curriculum/en-rules-v1.json"
LAT = "schema-math"


def _ready() -> tuple[dict, dict]:
    bundle = json.loads(BUNDLE.read_text(encoding="utf-8"))
    state = ensure_prisms({})
    ingest_math_bundle(state, bundle)
    data = json.loads(CLAUSE.read_text(encoding="utf-8"))
    teach_glossary(state, [tuple(p) for p in data["glossary"]], bundle=bundle)
    rules = json.loads(RULES.read_text(encoding="utf-8"))["rules"]
    for rid in ("lang.rule.present3sg.en", "lang.rule.past.en"):
        teach_conditioned_rule(state, LAT, rid, [tuple(p) for p in rules[rid]])
    teach_clause_constructions(state, LAT)
    return state, data


def test_six_constructions_generate_correctly() -> None:
    state, data = _ready()
    irr = data["irregular_past"]
    c = lambda **kw: compose_clause(state, LAT, subj="кот", verb="пить", obj="вода", irregular_past=irr, **kw)
    assert c(tense="present", polarity="affirmative", mood="declarative") == "The cat drinks the water."
    assert c(tense="present", polarity="negative", mood="declarative") == "The cat does not drink the water."
    assert c(tense="present", polarity="affirmative", mood="interrogative") == "Does the cat drink the water?"
    assert c(tense="past", polarity="affirmative", mood="declarative") == "The cat drank the water."  # irregular
    assert c(tense="past", polarity="negative", mood="declarative") == "The cat did not drink the water."
    assert c(tense="past", polarity="affirmative", mood="interrogative") == "Did the cat drink the water?"


def test_regular_verb_past_comes_from_the_rule() -> None:
    state, _ = _ready()
    # no irregular override: past form is generated by the learned past rule
    assert compose_clause(state, LAT, subj="девочка", verb="любить", obj="книга", tense="past") == "The girl loved the book."


def test_clause_gate_passes_with_controls() -> None:
    state, data = _ready()
    irr = data["irregular_past"]
    cases = [({**feat, "irregular_past": irr}, expected) for feat, expected in data["cases"]]
    rep = gate_clause_constructions(state, LAT, cases)
    assert rep["passed"] is True
    assert rep["held_out_pass_rate"] == 1.0
    assert rep["negative_control_passed"] is True
    assert rep["ablation_breaks_production"] is True
